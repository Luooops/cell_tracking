"""LaTeX tables (booktabs) -> out/tables.tex: test wells (all methods), 15-well comparison, HeLa.
LNK / CT / TRA are means over wells; ED (false), EA (missed), EC (wrong edge type) are AOGM terms summed over wells.
The best value of each column is bold."""
import data
import style

TEST = [('ours', 'Ours'), ('binary', 'Ours, binary edges'), ('v003', 'GNN v003 (scripta only)'),
        ('ta_ft', 'Trackastra fine-tuned'), ('ta_zs', 'Trackastra zero-shot'),
        ('ctgnn0', 'CellTrack-GNN, seed 0'), ('ctgnn1', 'CellTrack-GNN, seed 1'), ('classical', 'Classical')]
COLUMNS = [('LNK', 'LNK', 'mean', max, 4), ('CT', 'CT', 'mean', max, 3), ('TRA', 'TRA', 'mean', max, 4),
           ('AOGM_ED', 'ED', 'sum', min, 0), ('AOGM_EA', 'EA', 'sum', min, 0), ('AOGM_EC', 'EC', 'sum', min, 0)]


def table(rows, columns, caption, label):
    """rows: [(name, {column: value})] -> booktabs tabular, best of each column bold."""
    best = {c: pick(v[c] for _, v in rows) for c, _, _, pick, _ in columns}
    out = ['\\begin{table}[t]', '\\centering', '\\small', '\\setlength{\\tabcolsep}{4pt}',
           '\\begin{tabular}{l' + 'r' * len(columns) + '}', '\\toprule',
           'Method & ' + ' & '.join(h for _, h, *_ in columns) + ' \\\\', '\\midrule']
    for name, v in rows:
        cells = []
        for c, _, _, _, digits in columns:
            text = f'{v[c]:.{digits}f}' if digits else f'{int(round(v[c]))}'
            cells.append(f'\\textbf{{{text}}}' if v[c] == best[c] else text)
        out.append(f'{name} & ' + ' & '.join(cells) + ' \\\\')
    out += ['\\bottomrule', '\\end{tabular}', f'\\caption{{{caption}}}', f'\\label{{{label}}}', '\\end{table}', '']
    return '\n'.join(out)


def summary(t, columns):
    return {c: (t[c].mean() if how == 'mean' else t[c].sum()) for c, _, how, _, _ in columns}


def main():
    parts = ['% Generated by paper/figures/tables.py from development/final_results; do not edit by hand.', '']
    rows = [(name, summary(data.scripta_wells(k, data.TEST_WELLS), COLUMNS)) for k, name in TEST]
    parts.append(table(rows, COLUMNS, 'Test wells (r16c02, r01c20, r07c07) of scripta. CTC measures on fixed '
                       'detections with the project ground truth (not comparable with the CTC leaderboard). '
                       'LNK, CT, TRA: mean over wells; ED, EA, EC: AOGM terms (false, missed, wrong-type edges) '
                       'summed over wells.', 'tab:test'))
    keys = [('ours', 'Ours'), ('ta_ft', 'Trackastra fine-tuned'), ('ta_zs', 'Trackastra zero-shot')]
    cols15 = [c for c in COLUMNS if c[0] != 'AOGM_EC']
    rows = [(name, summary(data.scripta_wells(k, data.all_wells()), cols15)) for k, name in keys]
    parts.append(table(rows, cols15, 'All 15 scripta wells: 12 development wells out-of-fold (3 folds) and the 3 test '
                       'wells with the final models. Ours is higher than both Trackastra variants in LNK and CT on '
                       'every well (Wilcoxon $p = 6\\times10^{-5}$).', 'tab:all15'))
    hela_cols = [('LNK', 'LNK', 'mean', max, 3), ('CT', 'CT', 'mean', max, 3), ('BC(0)', 'BC', 'mean', max, 3),
                 ('div_recall', 'Div. recall', 'mean', max, 3), ('fp_div(0)', 'False div.', 'sum', min, 0)]
    rows = []
    for k, name in (('ours', 'Ours (LOSO)'), ('ta_zs', 'Trackastra zero-shot'),
                    ('ta_zs_ctc', 'Trackastra zero-shot (ctc)$^\\dagger$')):
        t = data.hela_wells(k)
        for seq in t.index:
            rows.append((f'{name}, {seq}', {c: t.loc[seq, c] for c, *_ in hela_cols}))
    parts.append(table(rows, hela_cols, 'Fluo-N2DL-HeLa, per sequence. Ours: trained on scripta and the other '
                       'sequence. $^\\dagger$Trained on all CTC ground truth, including these sequences.', 'tab:hela'))
    style.OUT.mkdir(parents=True, exist_ok=True)
    (style.OUT / 'tables.tex').write_text('\n'.join(parts), encoding='utf-8')
    print('written', style.OUT / 'tables.tex')


if __name__ == '__main__':
    main()
